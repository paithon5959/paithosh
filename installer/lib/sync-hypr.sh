#!/usr/bin/env bash
set -euo pipefail

# Sync Paithosh default Hyprland Lua config into ~/.config/hypr,
# with staging + Lua syntax validation, collision-safe backups,
# 3-way manifest updates, and JSON status reporting.

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"
MODE="replace"
DO_BACKUP="true"
NO_RELOAD="false"
DRY_RUN="false"
STATUS_ONLY="false"

require_arg() {
    if [[ "$1" -lt 2 || -z "${2:-}" ]]; then
        echo "[paithosh] Missing value for option '$3'" >&2
        exit 2
    fi
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --repo-root)
            require_arg $# "${2:-}" "$1"
            REPO_ROOT="$2"
            shift 2
            ;;
        --mode)
            require_arg $# "${2:-}" "$1"
            case "$2" in
                replace|update) MODE="$2" ;;
                *)
                    echo "[paithosh] Invalid mode '$2' (expected: replace | update)" >&2
                    exit 2
                    ;;
            esac
            shift 2
            ;;
        --if-needed)
            MODE="update"
            shift
            ;;
        --no-backup)
            DO_BACKUP="false"
            shift
            ;;
        --no-reload)
            NO_RELOAD="true"
            shift
            ;;
        --dry-run)
            DRY_RUN="true"
            shift
            ;;
        --status)
            STATUS_ONLY="true"
            shift
            ;;
        *)
            echo "[paithosh] Unknown option: $1" >&2
            exit 2
            ;;
    esac
done

if [[ "$REPO_ROOT" != "/" ]]; then
    REPO_ROOT="${REPO_ROOT%/}"
    [[ -z "$REPO_ROOT" ]] && REPO_ROOT="/"
fi

SRC_DIR="${REPO_ROOT}/defaults/hypr"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
HYPR_DIR="${CONFIG_HOME}/hypr"
MANIFEST_FILE="${HYPR_DIR}/.paithosh-manifest"
MARKER_FILE="${HYPR_DIR}/.paithosh-sync-version"

if [[ ! -d "$SRC_DIR" ]]; then
    echo "[paithosh] Missing default Hyprland config directory: $SRC_DIR" >&2
    exit 1
fi

STAGING_DIR=""
cleanup_staging() {
    if [[ -n "${STAGING_DIR:-}" && -d "${STAGING_DIR:-}" ]]; then
        rm -rf "$STAGING_DIR"
    fi
}
trap cleanup_staging EXIT

sha256_file() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    else
        python3 -c 'import hashlib, sys; print(hashlib.sha256(open(sys.argv[1], "rb").read()).hexdigest())' "$1"
    fi
}

compute_defaults_hash() {
    local combined=""
    local rel f h
    while IFS= read -r -d '' f; do
        rel="${f#"${SRC_DIR}"/}"
        [[ "$rel" == "config/paithosh.lua" ]] && continue
        h="$(sha256_file "$f")"
        combined+="${rel} ${h}"$'\n'
    done < <(find "$SRC_DIR" -type f -print0 | LC_ALL=C sort -z)

    local digest
    if command -v sha256sum >/dev/null 2>&1; then
        digest="$(printf '%s' "$combined" | sha256sum | awk '{print substr($1, 1, 12)}')"
    else
        digest="$(printf '%s' "$combined" | python3 -c 'import hashlib, sys; print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest()[:12])')"
    fi
    printf 'lua-defaults-%s\n' "$digest"
}

write_paithosh_lua() {
    local target_dir="$1"
    local escaped_root="${REPO_ROOT//\\/\\\\}"
    escaped_root="${escaped_root//\"/\\\"}"
    mkdir -p "${target_dir}/config"
    cat > "${target_dir}/config/paithosh.lua" <<EOF
-- Auto-generated by Paithosh sync-hypr.sh
return {
    root = "${escaped_root}",
}
EOF
}

write_manifest() {
    local target_dir="$1"
    local defaults_hash="$2"
    local tmp_manifest="${target_dir}/.paithosh-manifest"
    : > "$tmp_manifest"
    local f rel h
    while IFS= read -r -d '' f; do
        rel="${f#"${SRC_DIR}"/}"
        [[ "$rel" == "config/paithosh.lua" ]] && continue
        h="$(sha256_file "$f")"
        printf '%s  %s\n' "$h" "$rel" >> "$tmp_manifest"
    done < <(find "$SRC_DIR" -type f -print0 | LC_ALL=C sort -z)
    printf '%s\n' "$defaults_hash" > "${target_dir}/.paithosh-sync-version"
}

validate_lua() {
    local dir="$1"
    local f
    if command -v luac >/dev/null 2>&1; then
        while IFS= read -r -d '' f; do
            luac -p "$f" || return 1
        done < <(find "$dir" -name '*.lua' -print0)
    elif command -v luajit >/dev/null 2>&1; then
        while IFS= read -r -d '' f; do
            luajit -bl "$f" /dev/null || return 1
        done < <(find "$dir" -name '*.lua' -print0)
    elif command -v lua >/dev/null 2>&1; then
        while IFS= read -r -d '' f; do
            lua -e 'assert(loadfile(arg[1]))' "$f" || return 1
        done < <(find "$dir" -name '*.lua' -print0)
    fi
}

make_unique_backup_path() {
    local base="${HYPR_DIR}.bak.$(date +%Y%m%d_%H%M%S)"
    local cand="$base"
    local idx=1
    while [[ -e "$cand" || -L "$cand" ]]; do
        cand="${base}.${idx}"
        idx=$((idx + 1))
    done
    printf '%s\n' "$cand"
}

inspect_sync_plan_json() {
    local defaults_hash="$1"
    python3 - "$SRC_DIR" "$HYPR_DIR" "$REPO_ROOT" "$defaults_hash" <<'PY'
import hashlib, json, os, sys

src_dir, hypr_dir, repo_root, defaults_hash = sys.argv[1:5]

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()

def expected_paithosh_lua(root):
    escaped = root.replace("\\", "\\\\").replace('"', '\\"')
    return f'-- Auto-generated by Paithosh sync-hypr.sh\nreturn {{\n    root = "{escaped}",\n}}\n'

manifest_path = os.path.join(hypr_dir, ".paithosh-manifest")
marker_path = os.path.join(hypr_dir, ".paithosh-sync-version")

src_files = {}
for base, _, files in os.walk(src_dir):
    for fn in files:
        full = os.path.join(base, fn)
        rel = os.path.relpath(full, src_dir).replace(os.sep, "/")
        if rel == "config/paithosh.lua":
            continue
        src_files[rel] = sha256(full)

installed_hash = ""
if os.path.isfile(marker_path):
    try:
        installed_hash = open(marker_path, "r", encoding="utf-8").read().strip()
    except OSError:
        installed_hash = ""

has_manifest = os.path.isfile(manifest_path)
exists_or_link = os.path.lexists(hypr_dir)

non_hidden_count = 0
if os.path.isdir(hypr_dir) and not os.path.islink(hypr_dir):
    for base, dirs, files in os.walk(hypr_dir):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        for fn in files:
            if not fn.startswith("."):
                non_hidden_count += 1

if not exists_or_link or (os.path.isdir(hypr_dir) and not os.path.islink(hypr_dir) and non_hidden_count == 0 and not has_manifest):
    print(json.dumps({
        "state": "missing",
        "managed": False,
        "hyprDir": hypr_dir,
        "defaultsHash": defaults_hash,
        "installedHash": installed_hash,
        "addedFiles": sorted(src_files.keys()),
        "updatedFiles": [],
        "pendingFiles": sorted(src_files.keys()),
        "modifiedFiles": [],
        "rootMismatch": False,
    }))
    sys.exit(0)

if not has_manifest:
    print(json.dumps({
        "state": "unmanaged",
        "managed": False,
        "hyprDir": hypr_dir,
        "defaultsHash": defaults_hash,
        "installedHash": installed_hash,
        "addedFiles": [],
        "updatedFiles": [],
        "pendingFiles": [],
        "modifiedFiles": [],
        "rootMismatch": False,
    }))
    sys.exit(0)

manifest = {}
try:
    with open(manifest_path, "r", encoding="utf-8") as mf:
        for line in mf:
            line = line.rstrip("\r\n")
            if not line or "  " not in line:
                continue
            digest, rel = line.split("  ", 1)
            manifest[rel] = digest.strip()
except OSError:
    manifest = {}

added = []
updated = []
modified = []

for rel in sorted(src_files.keys()):
    src_sha = src_files[rel]
    cur_path = os.path.join(hypr_dir, rel)
    if not os.path.isfile(cur_path):
        added.append(rel)
        continue
    cur_sha = sha256(cur_path)
    base_sha = manifest.get(rel)
    if base_sha is not None and cur_sha == base_sha:
        if cur_sha != src_sha:
            updated.append(rel)
    elif cur_sha != src_sha:
        modified.append(rel)

paithosh_lua_path = os.path.join(hypr_dir, "config", "paithosh.lua")
root_mismatch = True
if os.path.isfile(paithosh_lua_path):
    try:
        root_mismatch = (open(paithosh_lua_path, "r", encoding="utf-8").read() != expected_paithosh_lua(repo_root))
    except OSError:
        root_mismatch = True

pending = added + updated
state = "outdated" if (pending or root_mismatch) else "synced"

print(json.dumps({
    "state": state,
    "managed": True,
    "hyprDir": hypr_dir,
    "defaultsHash": defaults_hash,
    "installedHash": installed_hash,
    "addedFiles": added,
    "updatedFiles": updated,
    "pendingFiles": pending,
    "modifiedFiles": modified,
    "rootMismatch": root_mismatch,
}))
PY
}

atomic_swap_staging() {
    local backup_dir=""
    if [[ -e "$HYPR_DIR" || -L "$HYPR_DIR" ]]; then
        if [[ "$DO_BACKUP" == "true" ]]; then
            backup_dir="$(make_unique_backup_path)"
            mv "$HYPR_DIR" "$backup_dir"
            if ! mv "$STAGING_DIR" "$HYPR_DIR"; then
                mv "$backup_dir" "$HYPR_DIR" || true
                echo "[paithosh] Failed to move staged Hyprland config into place; restored backup." >&2
                exit 1
            fi
            STAGING_DIR=""
            echo "[paithosh] Backed up existing Hyprland config to $backup_dir"
        else
            local old_tmp="${HYPR_DIR}.old.$$"
            while [[ -e "$old_tmp" || -L "$old_tmp" ]]; do
                old_tmp="${old_tmp}.x"
            done
            mv "$HYPR_DIR" "$old_tmp"
            if ! mv "$STAGING_DIR" "$HYPR_DIR"; then
                mv "$old_tmp" "$HYPR_DIR" || true
                echo "[paithosh] Failed to move staged Hyprland config into place; restored previous config." >&2
                exit 1
            fi
            STAGING_DIR=""
            rm -rf "$old_tmp"
        fi
    else
        if ! mv "$STAGING_DIR" "$HYPR_DIR"; then
            echo "[paithosh] Failed to install staged Hyprland config to $HYPR_DIR" >&2
            exit 1
        fi
        STAGING_DIR=""
    fi
}

reload_hyprland() {
    if [[ "$NO_RELOAD" != "true" ]] && command -v hyprctl >/dev/null 2>&1; then
        hyprctl reload >/dev/null 2>&1 || true
        echo "[paithosh] Hot-reloaded Hyprland"
    fi
}

DEFAULTS_HASH="$(compute_defaults_hash)"

if [[ "$STATUS_ONLY" == "true" ]]; then
    inspect_sync_plan_json "$DEFAULTS_HASH"
    exit 0
fi

if [[ "$MODE" == "replace" ]]; then
    if [[ "$DRY_RUN" == "true" ]]; then
        if [[ ( -e "$HYPR_DIR" || -L "$HYPR_DIR" ) && "$DO_BACKUP" == "true" ]]; then
            echo "[dry-run] Would back up $HYPR_DIR -> $(make_unique_backup_path)"
        fi
        echo "[dry-run] Would sync default Hyprland config ($DEFAULTS_HASH) from $SRC_DIR to $HYPR_DIR"
        exit 0
    fi

    mkdir -p "$CONFIG_HOME"
    STAGING_DIR="$(mktemp -d "${HYPR_DIR}.staging.XXXXXX")"
    cp -a "${SRC_DIR}/." "$STAGING_DIR/"
    write_paithosh_lua "$STAGING_DIR"
    write_manifest "$STAGING_DIR" "$DEFAULTS_HASH"

    if ! validate_lua "$STAGING_DIR"; then
        echo "[paithosh] Lua syntax validation failed in staging; keeping existing $HYPR_DIR untouched" >&2
        exit 1
    fi

    atomic_swap_staging
    echo "[paithosh] Synced default Hyprland config ($DEFAULTS_HASH) to $HYPR_DIR"
    reload_hyprland
    exit 0
fi

# --mode update (3-way SHA256 manifest)
if [[ ! -e "$HYPR_DIR" && ! -L "$HYPR_DIR" ]] || [[ ! -f "$MANIFEST_FILE" ]]; then
    echo "[paithosh] Custom or unmanaged Hyprland config at $HYPR_DIR — skipping auto-sync."
    exit 0
fi

PLAN_JSON="$(inspect_sync_plan_json "$DEFAULTS_HASH")"
eval "$(python3 - "$PLAN_JSON" <<'PY'
import json, shlex, sys
d = json.loads(sys.argv[1])
print(f"PLAN_STATE={shlex.quote(d['state'])}")
print(f"PLAN_ROOT_MISMATCH={'true' if d['rootMismatch'] else 'false'}")
print("PLAN_ADDED=(" + " ".join(shlex.quote(x) for x in d["addedFiles"]) + ")")
print("PLAN_UPDATED=(" + " ".join(shlex.quote(x) for x in d["updatedFiles"]) + ")")
print("PLAN_MODIFIED=(" + " ".join(shlex.quote(x) for x in d["modifiedFiles"]) + ")")
PY
)"

if [[ "$PLAN_STATE" == "synced" ]]; then
    if [[ ${#PLAN_MODIFIED[@]} -gt 0 ]]; then
        echo "[paithosh] Hyprland config already up to date (preserved ${#PLAN_MODIFIED[@]} customized file(s): ${PLAN_MODIFIED[*]})"
    else
        echo "[paithosh] Hyprland config already up to date"
    fi
    exit 0
fi

if [[ "$DRY_RUN" == "true" ]]; then
    [[ ${#PLAN_ADDED[@]} -gt 0 ]] && echo "[dry-run] Would add Hyprland files: ${PLAN_ADDED[*]}"
    [[ ${#PLAN_UPDATED[@]} -gt 0 ]] && echo "[dry-run] Would update unmodified Hyprland files: ${PLAN_UPDATED[*]}"
    [[ "$PLAN_ROOT_MISMATCH" == "true" ]] && echo "[dry-run] Would update config/paithosh.lua root -> $REPO_ROOT"
    [[ ${#PLAN_MODIFIED[@]} -gt 0 ]] && echo "[dry-run] Would preserve customized Hyprland files: ${PLAN_MODIFIED[*]}"
    exit 0
fi

mkdir -p "$CONFIG_HOME"
STAGING_DIR="$(mktemp -d "${HYPR_DIR}.staging.XXXXXX")"
cp -a "${HYPR_DIR}/." "$STAGING_DIR/"

for rel in ${PLAN_ADDED[@]+"${PLAN_ADDED[@]}"} ${PLAN_UPDATED[@]+"${PLAN_UPDATED[@]}"}; do
    mkdir -p "$(dirname -- "${STAGING_DIR}/${rel}")"
    cp -a "${SRC_DIR}/${rel}" "${STAGING_DIR}/${rel}"
done

write_paithosh_lua "$STAGING_DIR"
write_manifest "$STAGING_DIR" "$DEFAULTS_HASH"

if ! validate_lua "$STAGING_DIR"; then
    echo "[paithosh] Lua syntax validation failed in update staging; keeping existing $HYPR_DIR untouched" >&2
    exit 1
fi

atomic_swap_staging
echo "[paithosh] Updated Hyprland config ($DEFAULTS_HASH): added=${#PLAN_ADDED[@]} updated=${#PLAN_UPDATED[@]} preserved=${#PLAN_MODIFIED[@]}"
[[ ${#PLAN_MODIFIED[@]} -gt 0 ]] && echo "[paithosh] Preserved user-modified files: ${PLAN_MODIFIED[*]}"
reload_hyprland
