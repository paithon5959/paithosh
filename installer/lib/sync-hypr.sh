#!/usr/bin/env bash
set -euo pipefail

# Sync Paithosh default Hyprland Lua config into ~/.config/hypr,
# automatically backing up any existing config and hot-reloading Hyprland.

SYNC_VERSION="2026-11-24-lua-defaults"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"
IF_NEEDED=false
NO_RELOAD=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        --repo-root)
            REPO_ROOT="$2"
            shift 2
            ;;
        --if-needed)
            IF_NEEDED=true
            shift
            ;;
        --no-reload)
            NO_RELOAD=true
            shift
            ;;
        *)
            echo "Unknown option: $1" >&2
            exit 2
            ;;
    esac
done

SRC_DIR="${REPO_ROOT}/defaults/hypr"
HYPR_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/hypr"
MARKER_FILE="${HYPR_DIR}/.paithosh-sync-version"

if [[ ! -d "$SRC_DIR" ]]; then
    echo "Missing default Hyprland config directory: $SRC_DIR" >&2
    exit 1
fi

if [[ "$IF_NEEDED" == "true" && -f "$MARKER_FILE" ]]; then
    if [[ "$(tr -d '[:space:]' < "$MARKER_FILE")" == "$SYNC_VERSION" ]]; then
        exit 0
    fi
fi

BACKUP_DIR=""
if [[ -e "$HYPR_DIR" ]]; then
    BACKUP_DIR="${HYPR_DIR}.bak.$(date +%Y%m%d-%H%M%S)"
    cp -a "$HYPR_DIR" "$BACKUP_DIR"
    echo "[paithosh] Backed up existing Hyprland config to $BACKUP_DIR"
fi

rm -rf "$HYPR_DIR"
mkdir -p "$HYPR_DIR"
cp -a "${SRC_DIR}/." "$HYPR_DIR/"

escaped_root="${REPO_ROOT//\\/\\\\}"
escaped_root="${escaped_root//\"/\\\"}"
cat > "${HYPR_DIR}/config/paithosh.lua" <<EOF
-- Auto-generated by Paithosh sync-hypr.sh
return {
    root = "${escaped_root}",
}
EOF

validate_lua() {
    local f
    if command -v luac >/dev/null 2>&1; then
        find "$HYPR_DIR" -name '*.lua' -exec luac -p {} +
    elif command -v luajit >/dev/null 2>&1; then
        while IFS= read -r -d '' f; do
            luajit -bl "$f" /dev/null || return 1
        done < <(find "$HYPR_DIR" -name '*.lua' -print0)
    fi
}

if ! validate_lua; then
    echo "[paithosh] Lua syntax validation failed; restoring backup" >&2
    rm -rf "$HYPR_DIR"
    if [[ -n "$BACKUP_DIR" && -e "$BACKUP_DIR" ]]; then
        cp -a "$BACKUP_DIR" "$HYPR_DIR"
    fi
    exit 1
fi

printf '%s\n' "$SYNC_VERSION" > "$MARKER_FILE"
echo "[paithosh] Synced default Hyprland config ($SYNC_VERSION) to $HYPR_DIR"

if [[ "$NO_RELOAD" != "true" ]] && command -v hyprctl >/dev/null 2>&1; then
    hyprctl reload >/dev/null 2>&1 || true
    echo "[paithosh] Hot-reloaded Hyprland"
fi
